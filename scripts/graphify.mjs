import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const targetDirs = ["apps/server/src", "apps/web/src", "packages/core/src", "packages/sync/src", "packages/ui/src"];

let md = "# Basalt Codebase Architecture Graph\n\n";
md += "> This file is automatically generated. It maps out the dependencies, exports, and relationships between all source code files to provide an LLM with highly compressed project context.\n\n";

function scanDir(dir) {
  if (!fs.existsSync(dir)) return;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      scanDir(fullPath);
    } else if (fullPath.endsWith(".ts") || fullPath.endsWith(".tsx")) {
      parseFile(fullPath);
    }
  }
}

function parseFile(filePath) {
  const content = fs.readFileSync(filePath, "utf-8");
  const relPath = path.relative(rootDir, filePath);
  
  const imports = [...content.matchAll(/import\s+(?:[^"']*?\s+from\s+)?['"](.*?)['"]/g)].map(m => m[1]);
  const exportsMatches = [...content.matchAll(/export\s+(?:const|let|var|function|class|interface|type|default(?:\s+function|\s+class)?)\s*([a-zA-Z0-9_]*)/g)]
    .map(m => m[1] || "default")
    .filter(Boolean);
  
  if (imports.length === 0 && exportsMatches.length === 0) return;

  md += `### \`${relPath}\`\n`;
  if (exportsMatches.length > 0) md += `- **Exports**: ${exportsMatches.join(", ")}\n`;
  if (imports.length > 0) md += `- **Imports**: ${imports.join(", ")}\n`;
  md += "\n";
}

for (const dir of targetDirs) {
  scanDir(path.join(rootDir, dir));
}

const outPath = path.join(rootDir, "codebase-graph.md");
fs.writeFileSync(outPath, md);
console.log(`Codebase graph successfully generated at: ${outPath}`);
