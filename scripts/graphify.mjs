// Regenerates codebase-graph.md: every source file with what it exports and
// imports, for an agent that needs the map before the code.
//
//   node scripts/graphify.mjs
//
// test/codebase-graph.test.ts fails when a source file is missing from the
// committed graph (audit REG-012): run this after adding or removing one.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const TARGET_DIRS = [
  "apps/server/src",
  "apps/web/src",
  "apps/mcp/src",
  "packages/core/src",
  "packages/schema/src",
  "packages/sync/src",
  "packages/ui/src",
];
const isSource = (f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f) && !f.endsWith(".d.ts");

function sources(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((e) => {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) return e.name === "test" ? [] : sources(full);
      return isSource(e.name) ? [full] : [];
    });
}

function entry(file) {
  const content = fs.readFileSync(file, "utf-8");
  const rel = path.relative(rootDir, file).split(path.sep).join("/");
  const imports = [...content.matchAll(/import\s+(?:[^"']*?\s+from\s+)?['"](.*?)['"]/g)].map((m) => m[1]);
  const exports = [...content.matchAll(/export\s+(?:async\s+function\*?|const|let|var|function\*?|class|interface|type|enum|default(?:\s+async)?(?:\s+function|\s+class)?)\s*([a-zA-Z0-9_]*)/g)].map(
    (m) => m[1] || "default",
  );
  if (imports.length === 0 && exports.length === 0) return "";
  let md = `### \`${rel}\`\n`;
  if (exports.length > 0) md += `- **Exports**: ${exports.join(", ")}\n`;
  if (imports.length > 0) md += `- **Imports**: ${imports.join(", ")}\n`;
  return `${md}\n`;
}

export function graph() {
  let md = "# Basalt Codebase Architecture Graph\n\n";
  md +=
    "> This file is generated by `node scripts/graphify.mjs`. It maps out the dependencies, exports, and relationships between all source code files (tests excluded) to provide an LLM with highly compressed project context.\n\n";
  for (const dir of TARGET_DIRS) for (const file of sources(path.join(rootDir, dir))) md += entry(file);
  return md;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outPath = path.join(rootDir, "codebase-graph.md");
  fs.writeFileSync(outPath, graph());
  console.log(`Codebase graph successfully generated at: ${outPath}`);
}
